import fs from 'node:fs';
import path from 'node:path';
import MarkdownIt from 'markdown-it';

const root = process.cwd();
const source = path.join(root, 'docs/eden/rector_review_2026-10/dabar_simple_2026-10-06/pages');
const entries = [
  ['repository-policies', '01_Repository_Policies', 'footer.link.repository-policies'],
  ['accessibility-statement', '02_Accessibility_Statement', 'footer.link.accessibility-statement'],
  ['privacy', '03_Privacy_Notice', 'footer.link.privacy-notice'],
  ['contact', '04_Contact', 'footer.link.contact'],
];
const markdown = new MarkdownIt({ html: false });
const heading = markdown.renderer.rules.heading_open;
markdown.renderer.rules.heading_open = (tokens, index, options, env, self) => {
  if (tokens[index].tag === 'h2') {
    tokens[index].attrSet('id', tokens[index + 1].content.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''));
  }
  return heading ? heading(tokens, index, options, env, self) : self.renderToken(tokens, index, options);
};
const documents = {};
for (const [route, stem, labelKey] of entries) {
  const text = fs.readFileSync(path.join(source, `${stem}.md`), 'utf8');
  documents[route] = {
    title: text.split('\n')[0].replace(/^# /, ''),
    labelKey,
    html: markdown.render(text).replaceAll('https://repository.uist.edu.mk/info/contact', '/info/contact'),
  };
}
const output = path.join(root, 'src/app/info/repository-policies/repository-policy-documents.ts');
const content = '// Generated by scripts/build-repository-policies.mjs from the simplified UIST policy sources.\n' +
  "export const REPOSITORY_POLICY_VERSION = '2026-10-06-simple';\n\n" +
  'export interface RepositoryPolicyDocument {\n  title: string;\n  labelKey: string;\n  html: string;\n}\n\n' +
  'export const REPOSITORY_POLICY_DOCUMENTS: Record<string, RepositoryPolicyDocument> = ' +
  JSON.stringify(documents, null, 2) + ';\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== content) {
    throw new Error('Repository page content is out of date. Run node scripts/build-repository-policies.mjs.');
  }
} else {
  fs.writeFileSync(output, content);
}
